# Task H part 4: opponent / win-objective data from the 2025-26 league history. Run: python3 -E research/h_part4.py
# Inputs: research/data/season.json (managers' final lineups), research/out/h/r25_* (traced: human slots matched to games,
# hindsight lineup, game mu/sd), research/out/s10_* (P10 / P10b real totals), research/out/p11/a25m_* (P11 win-phase logs).
import json, glob, math, statistics as St
from collections import defaultdict
OUT = 'research/out/h'
S = json.load(open('research/data/season.json'))
opp = {}
for W in S['weeks']:
    for a, b in W.get('matchups') or []:
        opp[(W['week'], str(a))] = str(b); opp[(W['week'], str(b))] = str(a)
H = {}
for f in glob.glob(f'{OUT}/r25_*.json'):
    d = json.load(open(f)); H[(d['week'], d['rid'])] = d
s10 = {}
for f in glob.glob('research/out/s10_*.json'):
    d = json.load(open(f)); s10[(d['week'], d['rid'])] = {k: v['real'] for k, v in d['pols'].items()}
ci = lambda xs: (St.mean(xs), 1.96 * St.stdev(xs) / math.sqrt(len(xs))) if len(xs) > 1 else (xs[0] if xs else float('nan'), float('nan'))
L = ['# Part 4 tables (generated by research/h_part4.py)', '']

# ---------- per-manager behaviour ----------
man = defaultdict(lambda: defaultdict(list))
for (w, r), d in H.items():
    hu = d.get('human')
    if not hu: continue
    m = man[r]; g = d['games']; m['total'].append(hu['total']); m['hasOpp'].append((w, r) in opp)
    z_lock, zero, last, lockT = [], 0, 0, []
    for sl in hu['slots']:
        if sl['how'] in ('none', 'unmatched', 'offroster') or not sl['x']: zero += 1; continue
        gi = sl['g']; mu, sd = g[gi][5], g[gi][6]
        if sl['how'] == 'end': last += 1
        else:
            z_lock.append((sl['x'] - mu) / sd)
            # how much of the deadline window was used is unknown (only value time); record games the player had left
            later = [x for x in g if x[0] == sl['p'] and x[1] > g[gi][2]]
            lockT.append(len(later))
    m['zeroSlots'].append(zero); m['lastShare'].append(last / max(1, 9 - zero)); m['zLock'] += z_lock; m['gamesLeftAtLock'] += lockT
    m['hsGap'].append(d['hs']['total'] - hu['total'])
    if 'P8' in d['pols']: m['p8Gap'].append(d['pols']['P8']['total'] - hu['total'])
L += ['## Managers (2025-26, final lineups matched to games)', '',
      '| roster | weeks | mean total | sd | weeks < 150 pts | zero/empty slots per week | share of counted slots from the final game | mean z of locked scores (score − model mean)/sd | games left when a score is locked | P8 − manager (pts/wk) |',
      '|---|---|---|---|---|---|---|---|---|---|']
rowsM = []
for r in sorted(man, key=lambda x: int(x)):
    m = man[r]; t = m['total']
    rowsM.append(dict(r=r, n=len(t), mean=St.mean(t), sd=St.stdev(t), low=sum(1 for x in t if x < 150), zero=St.mean(m['zeroSlots']), last=St.mean(m['lastShare']), z=St.mean(m['zLock']) if m['zLock'] else float('nan'), gl=St.mean(m['gamesLeftAtLock']) if m['gamesLeftAtLock'] else float('nan'), p8=St.mean(m['p8Gap']) if m['p8Gap'] else float('nan')))
    x = rowsM[-1]
    L.append(f"| {r} | {x['n']} | {x['mean']:.1f} | {x['sd']:.1f} | {x['low']} | {x['zero']:.2f} | {100*x['last']:.0f}% | {x['z']:+.2f} | {x['gl']:.2f} | {x['p8']:+.1f} |")
# heterogeneity test: between-manager variance of weekly totals vs within (one-way ANOVA F)
allt = [(r, x) for r in man for x in man[r]['total']]; gm = St.mean(x for _, x in allt)
k = len(man); N = len(allt)
ssb = sum(len(man[r]['total']) * (St.mean(man[r]['total']) - gm) ** 2 for r in man); ssw = sum((x - St.mean(man[r]['total'])) ** 2 for r, x in allt)
F = (ssb / (k - 1)) / (ssw / (N - k))
# same for zero slots and lock z
def anova(key):
    groups = [man[r][key] for r in man if len(man[r][key]) > 1]; allv = [x for gq in groups for x in gq]; gmv = St.mean(allv)
    sb = sum(len(gq) * (St.mean(gq) - gmv) ** 2 for gq in groups); sw = sum((x - St.mean(gq)) ** 2 for gq in groups for x in gq)
    return (sb / (len(groups) - 1)) / (sw / (len(allv) - len(groups))), len(groups) - 1, len(allv) - len(groups)
Fz = anova('zeroSlots'); Fl = anova('zLock')
L += ['', f'Between-manager heterogeneity (one-way ANOVA F; F ≈ 1 = no manager effect): weekly total F = {F:.2f} (df {k-1}, {N-k}); zero/empty slots per week F = {Fz[0]:.2f} (df {Fz[1]}, {Fz[2]}); z of locked scores F = {Fl[0]:.2f} (df {Fl[1]}, {Fl[2]}). (F_crit at 5% ≈ 1.9.)', '']
# persistence: does a manager's previous-weeks mean predict this week (beyond the league mean)?
pairs = []
for r in man:
    t = man[r]['total']
    for i in range(3, len(t)): pairs.append((St.mean(t[:i]) - gm, t[i] - gm))
if pairs:
    mx = St.mean(a for a, _ in pairs); my = St.mean(b for _, b in pairs)
    cov = sum((a - mx) * (b - my) for a, b in pairs) / len(pairs); vx = St.mean((a - mx) ** 2 for a, _ in pairs); vy = St.mean((b - my) ** 2 for _, b in pairs)
    L.append(f'Walk-forward predictability: corr(manager\'s mean of earlier weeks, this week) = {cov / math.sqrt(vx * vy):.2f} over {len(pairs)} team-weeks (weeks ≥ 4).\n')

# ---------- margins vs the real opponent, winnable losses ----------
L += ['## Our engine vs the real opponents (2025-26 real outcomes, team-weeks with an opponent)', '']
res = defaultdict(list)
for (w, r), d in H.items():
    o = opp.get((w, r))
    if not o or (w, r) not in s10: continue
    od = H.get((w, o));
    if not od or not od.get('human'): continue
    oppT = od['human']['total']
    for pn in ('P10', 'P10b'):
        if pn in s10[(w, r)]: res[pn].append((s10[(w, r)][pn] - oppT, d['hs']['total'] - oppT, d['hs']['total'], s10[(w, r)][pn]))
for pn, lst in res.items():
    n = len(lst); m = [x[0] for x in lst]
    wins = sum(1 for x in m if x > 0); losses = [x for x in lst if x[0] < 0]
    L.append(f'**{pn}** ({n} team-weeks): win {100*wins/n:.1f}%; margin p10/p50/p90 {sorted(m)[n//10]:+.0f} / {St.median(m):+.0f} / {sorted(m)[9*n//10]:+.0f} pts.')
    L.append(f'- Losses: {len(losses)}; within 5 / 10 / 20 pts: {sum(1 for x in losses if x[0] > -5)} / {sum(1 for x in losses if x[0] > -10)} / {sum(1 for x in losses if x[0] > -20)}; '
             f'losses where even perfect hindsight on our side loses ("unwinnable"): {sum(1 for x in losses if x[1] < 0)}; winnable losses: {sum(1 for x in losses if x[1] >= 0)} ({100*sum(1 for x in losses if x[1] >= 0)/n:.1f}% of weeks = the oracle ceiling on win-rate gain from our own decisions).')
    wins_l = [x for x in lst if x[0] > 0]
    L.append(f'- Wins within 5 / 10 / 20 pts (could have been lost by riskier play): {sum(1 for x in wins_l if x[0] < 5)} / {sum(1 for x in wins_l if x[0] < 10)} / {sum(1 for x in wins_l if x[0] < 20)}.\n')

# ---------- P11 win-phase logs: how open is the week when the win objective switches on? ----------
pw0, pwAll, pwWin = [], [], []
for f in glob.glob('research/out/p11/a25m_*.json'):
    d = json.load(open(f))
    for pn, v in d['pols'].items():
        lg = (v.get('stats') or {}).get('win', {}).get('log') or []
        if lg: pw0.append(lg[0][6]); pwAll.append([x[6] for x in lg]); pwWin.append((lg[0][6], v.get('win')))
if pw0:
    n = len(pw0); b = lambda lo, hi: sum(1 for x in pw0 if lo <= x < hi) / n
    L += ['## Win probability when P11\'s win phase starts (3 game days left; real 2025-26, `p11/a25m` logs)', '',
          f'{n} team-weeks. P(win) at the first win-phase decision: < 0.05: {100*b(0,0.05):.0f}%; 0.05-0.25: {100*b(0.05,0.25):.0f}%; 0.25-0.75: {100*b(0.25,0.75):.0f}%; 0.75-0.95: {100*b(0.75,0.95):.0f}%; ≥ 0.95: {100*b(0.95,1.01):.0f}%.',
          f'Mean |change| in P(win) from the first to the last win-phase decision: {St.mean(abs(x[-1]-x[0]) for x in pwAll):.3f}.', '',
          '| predicted P(win) at 3 game days left | weeks | mean predicted | realized win rate |', '|---|---|---|---|']
    for lo, hi in ((0, .5), (.5, .75), (.75, .9), (.9, .97), (.97, 1.01)):
        sel = [(a, w) for a, w in pwWin if lo <= a < hi and w is not None]
        if sel: L.append(f'| {lo:.2f}-{min(hi,1):.2f} | {len(sel)} | {St.mean(a for a, _ in sel):.2f} | {St.mean(1.0 if w == 1 else 0.5 if w == 0.5 else 0.0 for _, w in sel):.2f} |')
    L.append('')
open(f'{OUT}/part4.md', 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))
